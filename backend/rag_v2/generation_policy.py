"""Trusted task-specific grounding instructions, independent of source text."""
from typing import Optional


def system_context_policy(response_policy: Optional[str]) -> str:
    if response_policy != "dispute_practice":
        return ""
    return (
        "Уточнение правил для практики налоговых споров:\n"
        "Если пользователь просит найти и кратко пересказать решения или их содержание, "
        "прямым ответом считается точный пересказ относящихся к вопросу фактов, доводов "
        "или правовой позиции, явно содержащихся в предоставленных фрагментах. "
        "Для такого обзора не требуется, чтобы пользователь указал номер дела или чтобы "
        "фрагмент содержал полный текст решения. Если итог спора в фрагменте отсутствует, "
        "прямо укажите это; не восстанавливайте исход дела по догадке. "
        "Если запрошен конкретный номер дела, пересказ другого дела не является ответом. "
        "Если фрагменты не содержат относящихся к вопросу фактов или доводов, применяется "
        "правило отказа. Нельзя выдавать упоминание суда за содержание судебного решения, "
        "приписывать доводы стороны суду или обобщать отдельное решение в универсальное правило. "
        "Эти ограничения одинаковы для русского, английского и грузинского ответа."
    )
